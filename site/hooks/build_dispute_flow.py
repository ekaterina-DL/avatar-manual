import re

from _build_profile import is_pdf_build

# Точное соответствие исходному тексту 3 пунктов раздела "Как устроено оспаривание ошибки"
# (manual-2-etap/00-overview.md) — без нечёткого сопоставления. Если исходный текст изменится,
# regex просто не совпадёт и хук ничего не сделает (на сайте останется исходный список).
# Пункт 3 переносится на вторую строку («   объясняет почему.») — концовка регэкспа собрана как
# lookahead на пустую строку (а не литеральный "\n"), иначе нежадный ".*?\n" в самом конце цепочки
# останавливается на первом же переносе и не захватывает вторую строку пункта — она "утекает"
# в текст после уже собранной схемы (найдено вживую: строка осталась висеть под диаграммой).
_LIST_RE = re.compile(
    r"1\. Асессор пишет в тред Mattermost.*?\n"
    r"2\. Наставник из числа опытных асессоров валидирует запрос.*?\n"
    r"3\. Возражение передаётся заказчику.*?(?=\n\n)",
    re.S,
)

_DIAGRAM = (
    '<div class="apeal-flow">\n'
    '<div class="apeal-step">\n'
    '<span class="apeal-num">1</span><span class="apeal-title">Асессор</span>\n'
    "<p>не согласен с ОС → пишет в тред Mattermost со ссылкой на видео и аргументом</p>\n"
    "</div>\n"
    '<div class="apeal-arrow">→</div>\n'
    '<div class="apeal-step">\n'
    '<span class="apeal-num">2</span><span class="apeal-title">Наставник</span>\n'
    "<p>валидирует запрос → возвращает возражение или передаёт руководителю для дальнейшей\n"
    "отправки заказчику</p>\n"
    "</div>\n"
    '<div class="apeal-arrow">→</div>\n'
    '<div class="apeal-step">\n'
    '<span class="apeal-num">3</span><span class="apeal-title">Заказчик</span>\n'
    "<p>подтверждает (ошибку исправят) или нет — объясняет почему</p>\n"
    "</div>\n"
    "</div>"
)


def on_page_markdown(markdown, page, config, files):
    """Нумерованный список из раздела "Как устроено оспаривание ошибки" (manual-2-etap/00-overview.md)
    заменяет на компактную горизонтальную схему из 3 шагов — на сайте длинный список читался
    громоздко. Вступительное предложение перед списком и текст после списка — не трогает,
    заменяется только сам список. PDF-профиль не трогаем: он задуман как полный документ,
    список остаётся текстом в исходном виде."""
    if is_pdf_build(config):
        return markdown
    if page.file.src_uri.replace("\\", "/") != "manual-2-etap/00-overview.md":
        return markdown
    return _LIST_RE.sub("\n" + _DIAGRAM + "\n", markdown, count=1)
