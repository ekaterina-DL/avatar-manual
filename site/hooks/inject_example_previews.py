def _build_preview_markdown(mapping):
    if "items" in mapping:
        # Видео зашиты прямо в MAPPINGS, не читаются со страницы — см. комментарий у записи
        # "Тип речи" выше. max_items там всегда равен len(items), поэтому ветка "remaining > 0"
        # ниже для такого mapping не сработает.
        items = mapping["items"]
    else:
        source_path = DOCS_DIR / mapping["source_file"]
        source_text = source_path.read_text(encoding="utf-8")
        section_body = extract_section(source_text, mapping["source_heading"])
        if section_body is None:
            return None
        items = split_list_items(section_body)
    if not items:
        return None
    preview_items = items[: mapping["max_items"]]
    remaining = len(items) - len(preview_items)
    # Приватный маркер для group_media_lists.py (следующий хук в пайплайне): превью вставляется
    # посреди прозы целевой страницы, без собственного markdown-заголовка — без этой строки
    # group_media_lists.py взял бы эйброу .video-block из ближайшего ПРЕДЫДУЩЕГО настоящего
    # заголовка целевой страницы (например, "Уточнения по конкретным полям..."), а не из
    # названия поля, которому реально посвящено превью. group_media_lists.py распознаёт эту
    # строку, использует её как current_heading именно с этой точки документа и вырезает саму
    # строку из финального вывода — она не должна попасть в HTML как видимый текст.
    lines = [
        "",
        f'<!-- video-eyebrow: {mapping["label"]} -->',
        '<div markdown="1">',
    ]
    if not mapping.get("skip_label"):
        lines.append("**Примеры:**")
    lines.append("")
    lines.extend(preview_items)
    # Под каждым превью — ссылка-приглашение на страницу «Банк примеров» своего этапа, но только
    # когда там реально есть ЧТО показать сверх уже показанного здесь: пользователь 03.09.2026
    # потребовала, чтобы любая отсылка на банк примеров была подтверждена — там должны быть
    # действительно дополнительные видео, а не то же самое или вообще ничего. Раньше (02.09.2026)
    # здесь была третья ветка, которая для mapping с "items" (видео зашиты прямо в MAPPINGS, у
    # поля вообще нет своего раздела на странице «Банк примеров») всё равно ставила общую ссылку
    # на страницу целиком — это и есть тот неподтверждённый случай, который теперь запрещён.
    if remaining > 0:
        anchor = _slugify_heading(mapping["source_heading"], "-")
        link = f"{Path(mapping['source_file']).name}#{anchor}"
        lines.append(f"\n→ ещё {remaining} прим. в [банке примеров]({link})")
    elif "source_file" in mapping:
        # Показаны уже все примеры этого раздела-источника (remaining == 0) — ссылка всё равно
        # ведёт прямо на его якорь: секция там реально существует, просто без "лишних" видео
        # сверх уже показанных здесь.
        anchor = _slugify_heading(mapping["source_heading"], "-")
        link = f"{Path(mapping['source_file']).name}#{anchor}"
        lines.append(f"\n→ больше примеров — в [банке примеров]({link})")
    # else: видео зашиты прямо в MAPPINGS ("items") — своего раздела на странице «Банк примеров»
    # для этого поля нет вообще, и никакой ссылки не ставится (до 03.09.2026 здесь была
    # неподтверждённая общая ссылка на страницу целиком — убрана).
    # Пустая строка обязательна перед закрывающим </div>: сейчас после списка примеров всегда
    # идёт ровно одна строка-ссылка (либо "ещё N", либо общая "больше примеров"), но исходно этот
    # разделитель защищал именно от случая remaining == 0, когда после последнего пункта списка
    # ничего не добавлялось вовсе, и </div> оказывался на строке сразу после него без пустой
    # строки-разделителя между ними. group_media_lists.py (следующий по порядку хук) сканирует
    # список видео-пунктов и останавливается только на пустой строке — без неё "</div>" ошибочно
    # затягивается внутрь последнего пункта как продолжение подписи, а _parse_video_item() затем
    # кладёт этот "</div>" прямо в caption, что даёт битую вложенность тегов на странице:
    # `<div class="vi-cap"><span markdown="1"></div></span></div>`. Обнаружено на
    # 04-classifier.md → превью "Ракурс" (ровно 2 примера в разделе-источнике = remaining 0).
    lines.append("")
    lines.append("</div>")
    lines.append("")
    return "\n".join(lines)


def _apply_mapping(markdown, mapping):
    preview = _build_preview_markdown(mapping)
    if preview is None:
        return markdown
    lines = markdown.split("\n")
    for idx, line in enumerate(lines):
        if mapping["anchor"] in line:
            insert_at = idx + 1 if mapping["position"] == "after_line" else idx
            new_lines = lines[:insert_at] + preview.split("\n") + lines[insert_at:]
            return "\n".join(new_lines)
    return markdown


def on_page_markdown(markdown, page, config, files):
    """Вставляет компактное превью (2-3 примера) из банка примеров рядом с конкретным полем
    классификатора/критерием — только там, где явно прописано соответствие в MAPPINGS. Ничего
    не выдумывает: если якорь или раздел-источник не найден, страница остаётся без изменений."""
    src_uri = page.file.src_uri.replace("\\", "/")
    applicable = [m for m in MAPPINGS if m["target_file"] == src_uri]
    if not applicable:
        return markdown
    for mapping in applicable:
        markdown = _apply_mapping(markdown, mapping)
    return markdown
