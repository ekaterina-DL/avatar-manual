def on_page_markdown(markdown, page, config, files):
    """Точечные сокращения текста на сайте, по одному разделу за раз, по запросу пользователя
    (см. REPLACEMENTS). Сам файл мануала не меняется, правка применяется на лету при сборке.
    PDF-профиль не трогаем — там остаётся полный исходный текст (PDF задуман как полный
    самостоятельный документ, см. hide_site_only_sections.py). Точное совпадение старого
    текста; если исходный текст успеет разойтись с этой копией — замена просто не сработает
    (без падения сборки)."""
    if is_pdf_build(config):
        return markdown
    src_uri = page.file.src_uri.replace("\\", "/")
    for old, new in REPLACEMENTS.get(src_uri, []):
        markdown = markdown.replace(old, new)
    return markdown
