import markdown

# Должно точно соответствовать site/mkdocs.yml -> markdown_extensions. slugify здесь не важен
# для рендеринга самого HTML (влияет только на id заголовков toc), поэтому используется базовая
# конфигурация toc без кастомного slugify — тесты не проверяют id заголовков.
EXTENSIONS = ["tables", "attr_list", "md_in_html", "toc"]


def render_html(markdown_text):
    """Рендерит markdown-текст (обычно — уже пропущенный через один или несколько хуков) через
    настоящую библиотеку markdown с тем же набором расширений, что использует сайт (см.
    site/mkdocs.yml -> markdown_extensions). Нужен, чтобы тесты хуков проверяли ФАКТИЧЕСКИ
    отрендеренный HTML (например, что markdown="1" действительно раскрывает **bold**/списки),
    а не просто промежуточную строку — вывод самого хука не показывает, работает ли markdown="1"
    так, как ожидается (см. Fix 1 итогового обзора: markdown="1" не является предком у ВСЕХ
    вложенных тегов, либо контент не на отдельной строке — тихо остаётся необработанным)."""
    return markdown.markdown(markdown_text, extensions=EXTENSIONS)
